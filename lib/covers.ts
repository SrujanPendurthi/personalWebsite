export const coverArt = (name: string): CoverPixel[] | null => {
  const rows = COVERS[name.toLowerCase()];
  if (!rows) return null;
  return rows.flatMap((row, y) =>
    [...row].flatMap((ch, x) => (ch === "." ? [] : [{ x, y, fill: PALETTE[ch] }])),
  );
};
